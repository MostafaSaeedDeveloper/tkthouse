import { chromium } from 'playwright-core';
const BASE = process.env.BASE_URL || 'http://localhost:8000';
const b = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium', args: ['--no-sandbox'] });
let pass=0, fail=0; const t=(n,ok,x='')=>{ok?pass++:fail++;console.log(`${ok?'PASS':'FAIL'}  ${n}${x?'  -> '+x:''}`)};
const c = await b.newContext({ viewport:{width:1200,height:900} }); const p = await c.newPage(); const errs=[]; p.on('pageerror',e=>errs.push(e.message)); await p.route(/^https?:\/\/(?!localhost)/, r=>r.abort());
await p.goto(BASE+'/login'); await p.fill('input[name=username]','auditadmin'); await p.fill('input[name=password]','Passw0rd!aud'); await Promise.all([p.waitForURL(u=>!u.pathname.startsWith('/login')),p.click('button[type=submit]')]);
await p.goto(BASE+'/dashboard/users/create'); await p.waitForTimeout(500);
const ticked = () => p.evaluate(()=>[...document.querySelectorAll('#u-perms input[type=checkbox]:checked')].map(i=>i.value).sort());
t('no role: nothing ticked', (await ticked()).length===0);
await p.selectOption('#u-role', 'support'); await p.waitForTimeout(200);
const sup = await ticked();
t('choosing Support ticks its permissions', sup.length===6 && sup.includes('orders.view'), sup.join(','));
t('"from role" badges and count shown', (await p.locator('.a-user-inherited:visible').count())===6 && /6 ticked · 6 from role · 0 extra/.test(await p.locator('[data-perm-count]').textContent()));
await p.locator('[data-perm-row="tickets.view"] input').check();
t('extra permission can be added', /7 ticked · 6 from role · 1 extra/.test(await p.locator('[data-perm-count]').textContent()));
await p.selectOption('#u-role', 'scanner'); await p.waitForTimeout(200);
const sc = await ticked();
t('switching role swaps the role permissions and keeps the hand-ticked extra', sc.includes('tickets.view') && sc.includes('scanner.access') && !sc.includes('reports.view') , sc.join(','));
await p.locator('[data-perm-row="scanner.access"] input').uncheck();
t('unticking a role permission shows the warning', await p.locator('[data-perm-warn]').isVisible(), (await p.locator('[data-perm-warn]').textContent()));
await p.locator('[data-perm-reset]').click();
t('Reset to role restores exactly the role permissions', JSON.stringify(await ticked())===JSON.stringify([...(await p.evaluate(()=>JSON.parse(document.getElementById('u-role').dataset.rolePerms).scanner))].sort()) && !(await p.locator('[data-perm-warn]').isVisible()));
// save with the role intact
const uname='permuser'+Date.now();
await p.fill('#u-name','Perm UI'); await p.fill('#u-username',uname); await p.fill('#u-email',uname+'@example.test'); await p.fill('#u-password','Secret123!');
await Promise.all([p.waitForURL(u=>!u.pathname.endsWith('/create')),p.click('button[type=submit]:has-text("Save"), form button.a-btn--primary[type=submit]')]);
t('saved without validation errors', !/create/.test(p.url()), p.url());
await p.goto(BASE+'/dashboard/users'); await p.waitForTimeout(300);
await p.fill('input[name=search]', uname).catch(()=>{});
const row = p.locator('a', { hasText: 'Perm UI' }).first();
await row.waitFor({ timeout: 5000 }).catch(()=>{});
t('no console errors', errs.length===0, errs.join(';'));
console.log(`\n${pass} passed, ${fail} failed`); await b.close();
